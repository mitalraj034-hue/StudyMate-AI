class GeminiService:
    """
    Centralized Google Gemini AI Service for StudyMate AI.
    Powered by the official Google Gen AI Python SDK (google-genai).
    
    Serves as the SINGLE central intelligence engine across:
      1. AI Chat & Personal Tutor (Modes, Learning Levels, English/Hindi/Hinglish, Comprehension Checks)
      2. Advanced Academic Summaries (Quick, Detailed, Chapter-wise, Exam Notes, Last-Minute Revision, Topic-wise)
      3. Dynamic MCQ Quiz Generation (100% generated by Gemini from PDF)
      4. Active Recall Flashcards (generated directly from PDF concepts)
      5. Structured Lecture Notes Generation
      6. 768-dimensional Dense Embeddings for pgvector & ChromaDB
    """

    def __init__(self):
        self.api_key = settings.GEMINI_API_KEY or os.getenv("GEMINI_API_KEY", "")
        self.model_name = getattr(settings, "GEMINI_MODEL", "gemini-3.5-flash-lite") or "gemini-3.5-flash-lite"
        self.dimension = 768
        self.timeout = 50.0
        self.base_url = "https://generativelanguage.googleapis.com/v1beta"
        self._init_sdk_client()

    def _init_sdk_client(self):
        """Initializes the official google-genai SDK client."""
        self.client = None
        key = self.get_api_key()
        if GENAI_AVAILABLE and key:
            try:
                opts = types.HttpOptions(timeout=35000) if (types and hasattr(types, "HttpOptions")) else None
                self.client = genai.Client(api_key=key, http_options=opts) if opts else genai.Client(api_key=key)
                logger.info(f"Official Google GenAI SDK client initialized (model: {self.model_name}).")
            except Exception as e:
                logger.warning(f"Could not initialize google-genai client: {e}")
                self.client = None

    def get_api_key(self) -> str:
        """Securely retrieves API key from settings or environment without leaking."""
        return (self.api_key or os.getenv("GEMINI_API_KEY", "")).strip().strip('"').strip("'")

    def is_configured(self) -> bool:
        """Checks if a valid Gemini API key is configured."""
        key = self.get_api_key()
        return bool(key and len(key) > 10 and not key.startswith("your_"))

    # =========================================================================
    # CORE SDK INVOCATION WITH REST FALLBACK & RETRIES
    # =========================================================================
    def generate_raw_text(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        json_mode: bool = False,
        temperature: float = 0.25
    ) -> str:
        """
        Executes text generation using the official google-genai SDK.
        Attempts primary model, with candidate fallbacks and direct REST if required.
        """
        key = self.get_api_key()
        if not key:
            raise ValueError("GEMINI_API_KEY is not configured in backend .env file.")

        # Ensure SDK client is ready
        if self.client is None and GENAI_AVAILABLE:
            self._init_sdk_client()

        # 1. Primary: Use Official google-genai SDK
        if self.client is not None and GENAI_AVAILABLE:
            config_params = {
                "temperature": 0.15 if json_mode else temperature,
                "top_p": 0.90,
                "top_k": 40,
                "max_output_tokens": 5000,
            }
            if json_mode:
                config_params["response_mime_type"] = "application/json"
            if system_instruction:
                config_params["system_instruction"] = system_instruction

            config = types.GenerateContentConfig(**config_params)

            # Models to attempt in order
            models_to_try = [self.model_name]
            for candidate in ["gemini-3.5-flash-lite", "gemini-3.8-flash", "gemini-flash-latest"]:
                if candidate not in models_to_try:
                    models_to_try.append(candidate)

            last_error = None
            for target_model in models_to_try:
                try:
                    response = self.client.models.generate_content(
                        model=target_model,
                        contents=prompt,
                        config=config
                    )
                    if response and hasattr(response, "text") and response.text:
                        self.model_name = target_model
                        return response.text
                except Exception as e:
                    last_error = e
                    logger.warning(f"google-genai SDK invocation ({target_model}) notice: {e}")

        # 2. Secondary: Direct REST API Fallback
        url = f"{self.base_url}/models/{self.model_name}:generateContent?key={key}"
        body: Dict[str, Any] = {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {
                "temperature": 0.15 if json_mode else temperature,
                "topP": 0.90,
                "topK": 40,
                "maxOutputTokens": 5000,
            }
        }
        if json_mode:
            body["generationConfig"]["responseMimeType"] = "application/json"
        if system_instruction:
            body["systemInstruction"] = {"parts": [{"text": system_instruction}]}

        try:
            with httpx.Client(timeout=25.0) as http_client:
                res = http_client.post(url, headers={"Content-Type": "application/json"}, json=body)
                if res.status_code == 200:
                    data = res.json()
                    candidates = data.get("candidates", [])
                    if candidates and "content" in candidates[0]:
                        parts = candidates[0]["content"].get("parts", [])
                        if parts:
                            return parts[0].get("text", "")
                else:
                    logger.warning(f"Gemini REST API status {res.status_code}: {res.text[:200]}")
        except Exception as err:
            logger.warning(f"REST attempt failed: {err}")

        raise RuntimeError(f"Google Gemini AI service error: {last_error or 'Could not complete generation.'}")

    # =========================================================================
    # 1. AI CHAT & PERSONAL TUTOR (INTELLIGENT GROUNDED PDF ASSISTANT)
    # =========================================================================
    def generate_chat_answer(
        self,
        query: str,
        retrieved_chunks: List[Dict[str, Any]],
        document_title: str = "Uploaded Document",
        conversation_history: Optional[List[Dict[str, str]]] = None,
        mode: str = "Detailed Explanation",
        level: str = "Intermediate",
        language: str = "English",
        action: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Synthesizes an academic answer grounded STRICTLY in retrieved PDF chunks.
        Acts as an intelligent, encouraging PERSONAL AI TUTOR:
          - Adapts to learning level (Beginner, Intermediate, Advanced)
          - Adapts to language (English, Hindi, Hinglish)
          - Adopts explanation mode (Simple, Step-by-Step, Exam Prep, Quick Revision, etc.)
          - Formats response with clear headings and includes a comprehension check
          - Provides actionable follow-up suggestion chips
        """
        # Build context blocks with exact page and chapter provenance
        context_parts = []
        citations = []
        if retrieved_chunks:
            for i, chunk in enumerate(retrieved_chunks[:10]):
                page_num = chunk.get("page_number", 1)
                chap = chunk.get("chapter", "General Section")
                content = chunk.get("content", "").strip()
                score = chunk.get("similarity", chunk.get("relevance_score", 92))
                score_pct = int(score * 100) if score <= 1.0 else int(score)
                score_pct = max(70, min(99, score_pct))

                context_parts.append(f"--- [EXCERPT {i+1} | PAGE {page_num} | {chap}] ---\n{content}")
                citations.append({
                    "page_number": page_num,
                    "chapter": chap,
                    "excerpt": content[:180] + ("..." if len(content) > 180 else ""),
                    "relevance_score": score_pct
                })
            context_text = "\n\n".join(context_parts)
        else:
            context_text = "No direct excerpts from the uploaded PDF matched this query."

        # Build conversation history context
        history_text = ""
        if conversation_history:
            history_lines = []
            for turn in conversation_history[-6:]:
                role = "Student" if turn.get("role") in ("user", "student") else "Tutor (StudyMate AI)"
                history_lines.append(f"{role}: {turn.get('content', '').strip()}")
            if history_lines:
                history_text = "RECENT CONVERSATION CONTEXT:\n" + "\n".join(history_lines) + "\n\n"

        # Mode-specific guidelines (conversational, not rigid)
        mode_instructions = {
            "Simple Explanation": "Focus on simplicity and clarity. Use everyday words, intuitive analogies, and avoid dense academic jargon.",
            "Step-by-Step Teaching": "Break down the concept into an intuitive, numbered step-by-step walkthrough.",
            "Detailed Explanation": "Provide a clear, well-structured explanation with depth, core mechanisms, and practical context.",
            "Exam Preparation": "Highlight exam-critical definitions, high-yield points, common exam pitfalls, and how to write answers for maximum marks.",
            "Quick Revision": "Synthesize crisp, high-yield bullet points for fast recall and exam review.",
            "Real-Life Examples": "Explain primarily through vivid, relatable everyday analogies and concrete real-world use cases."
        }
        selected_mode_text = mode_instructions.get(mode, mode_instructions["Detailed Explanation"])

        # Level-specific guidelines
        level_instructions = {
            "Beginner": "Target Level: Beginner. Use very simple language, relatable metaphors, and assume no prior background.",
            "Intermediate": "Target Level: Intermediate. Balance conceptual clarity with appropriate technical accuracy.",
            "Advanced": "Target Level: Advanced. In-depth university level, discussing architectural nuances and theoretical rigor."
        }
        selected_level_text = level_instructions.get(level, level_instructions["Intermediate"])

        # Language instructions
        lang_instructions = {
            "English": "Respond in clear, natural, friendly conversational English.",
            "Hindi": "Respond in simple, respectful Hindi (हिन्दी) in Devanagari script. Keep core technical terms in English/parentheses for clarity.",
            "Hinglish": "Respond in friendly, natural conversational Hinglish (Hindi written in Roman script, commonly spoken by students, e.g. 'Yeh concept bohot simple hai, chaliye samajhte hain...'). Keep technical terms in English."
        }
        selected_lang_text = lang_instructions.get(language, lang_instructions["English"])

        # Detect specific student intention cues from query
        q_lower = query.lower()
        intent_guidance = ""
        if "don't understand" in q_lower or "dont understand" in q_lower or "confused" in q_lower or "explain again" in q_lower:
            intent_guidance = (
                "IMPORTANT: The student did not understand the previous explanation. "
                "Do NOT repeat the previous words or definitions. Explain using a completely different, "
                "much simpler everyday analogy or mental picture. Keep it short and intuitive."
            )
        elif "make it shorter" in q_lower or "shorter" in q_lower or "summarize" in q_lower or "brief" in q_lower or action == "make_shorter":
            intent_guidance = (
                "IMPORTANT: The student wants a shorter answer. Provide a concise, 3-4 bullet point summary "
                "giving the essential core takeaways immediately."
            )
        elif "explain more" in q_lower or "more detail" in q_lower or action == "explain_more":
            intent_guidance = (
                "IMPORTANT: The student wants deeper knowledge. Go deeper into the underlying mechanisms, "
                "practical nuances, or advanced details without repeating what was already explained."
            )
        elif "example" in q_lower or action == "give_example":
            intent_guidance = (
                "IMPORTANT: The student is asking for an example. Give a fresh, relatable real-world example "
                "that connects directly to everyday life."
            )
        elif "ask me a question" in q_lower or "test me" in q_lower or "quiz me" in q_lower:
            intent_guidance = (
                "IMPORTANT: The student wants to test their knowledge. Ask 1 clear, thoughtful practice question "
                "related to the topic, and encourage them to answer."
            )
        elif "hinglish" in q_lower or action == "in_hinglish":
            selected_lang_text = lang_instructions["Hinglish"]
            intent_guidance = "IMPORTANT: Explain the topic naturally in conversational Hinglish."
        elif "hindi" in q_lower or action == "in_hindi":
            selected_lang_text = lang_instructions["Hindi"]
            intent_guidance = "IMPORTANT: Explain the topic in clear, natural Hindi."

        # Action overrides
        action_text = ""
        if action == "explain_more":
            action_text = "ACTION: Provide deeper academic insights and inner workings."
        elif action == "give_example":
            action_text = "ACTION: Provide a distinct, relatable everyday example."
        elif action == "make_shorter":
            action_text = "ACTION: Provide a concise, high-yield summary."
        elif action == "in_hindi":
            selected_lang_text = lang_instructions["Hindi"]
        elif action == "in_hinglish":
            selected_lang_text = lang_instructions["Hinglish"]

        system_instruction = (
            "You are StudyMate AI, an intelligent, friendly, and natural personal AI tutor — just like ChatGPT, but personalized for the student's study materials.\n\n"
            "TEACHING STYLE & RULES:\n"
            "1. Natural Conversational Tone: Talk like a patient, knowledgeable human teacher. Avoid robotic greetings ('Hello student!'), corporate filler, and repetitive textbook lectures.\n"
            "2. Direct Answer First: Always answer the student's specific question directly in the opening lines. No unnecessary introductions.\n"
            "3. Dynamic Length & Structure:\n"
            "   - Simple definition question -> Short, clear definition + 1 easy example + key takeaway. Do NOT write lengthy paragraphs.\n"
            "   - Chapter or broad concept -> Organized topic-by-topic breakdown in simple language.\n"
            "   - 'I still don't understand' -> Use a completely fresh, simpler analogy. Never repeat the previous explanation word-for-word.\n"
            "   - 'Make it shorter' -> 3-4 crisp bullet points.\n"
            "   - 'Give me an example' -> Practical, everyday scenario.\n"
            "   - 'Ask me a question' -> Exactly 1 thoughtful practice question to test concept understanding.\n"
            "   - Specific Page query ('Explain page 3') -> Focus directly on what is covered on that specific page.\n"
            "4. NO RIGID BOILERPLATE HEADINGS: NEVER output fixed headings like '### Direct Answer', '### Detailed Explanation', '### Important Points', '### Practical Examples', '### Conclusion', or '### Check Your Understanding'. Use clean Markdown (bold text, clean lists, short subheadings) ONLY when it genuinely improves readability.\n"
            "5. PDF Grounding: Base study explanations on the provided PDF excerpts and cite pages naturally (e.g. 'According to Page 3...' or '(Page 3)'). Do not fabricate facts.\n"
            "6. Off-Topic / General Questions: If the student asks something outside the PDF (e.g. 'What is the weather today?'), respond politely and naturally in 1-2 friendly sentences as general knowledge, warmly note that it's outside the uploaded PDF, and offer to continue with their document.\n"
            "7. Follow-up Context: Resolve pronouns ('it', 'its', 'these', 'them') and refer back to previous conversation turns smoothly.\n\n"
            f"- Tutor Tone & Level: {selected_level_text} | {selected_mode_text}\n"
            f"- Language: {selected_lang_text}\n"
            f"{intent_guidance}\n"
            f"{action_text}"
        )

        prompt = (
            f"SOURCE DOCUMENT: {document_title}\n\n"
            f"{history_text}"
            f"RETRIEVED DOCUMENT EXCERPTS:\n{context_text}\n\n"
            f"STUDENT QUESTION / INQUIRY: {query}\n\n"
            f"Provide a natural, conversational personal tutor response:"
        )

        try:
            gemini_reply = self.generate_raw_text(prompt, system_instruction=system_instruction, temperature=0.35)
            if gemini_reply.strip():
                # Formulate contextual interactive follow-up chips
                follow_ups = []
                if language != "Hinglish":
                    follow_ups.append("Explain in Hinglish 🇮🇳")
                else:
                    follow_ups.append("Explain in English 🇬🇧")

                follow_ups.append("Give an example 💡")
                follow_ups.append("Make it shorter ✂️")
                follow_ups.append("Ask me a question 📝")

                return {
                    "answer": gemini_reply.strip(),
                    "citations": citations[:4],
                    "confidence": citations[0]["relevance_score"] if citations else 94,
                    "grounded": True,
                    "mode": mode,
                    "level": level,
                    "language": language,
                    "follow_up_suggestions": follow_ups
                }
        except Exception as e:
            logger.error(f"Gemini Chat Generation failed: {e}")
            if not retrieved_chunks:
                return {
                    "answer": (
                        f"I couldn't find information about **\"{query}\"** in your uploaded document (*{document_title}*).\n\n"
                        f"If you're asking a general question or something outside your notes, "
                        f"feel free to ask about any topic or chapter directly from *{document_title}*!"
                    ),
                    "citations": [],
                    "confidence": 0,
                    "grounded": False,
                    "mode": mode,
                    "level": level,
                    "language": language,
                    "follow_up_suggestions": [
                        "What topics are covered in this PDF?",
                        "Summarize Chapter 1",
                        "Explain key definitions in this document"
                    ]
                }
            raise e

    # =========================================================================
    # 2. ADVANCED ACADEMIC SUMMARIES (COMPLETE PDF UNDERSTANDING & CUSTOM TYPES)
    # =========================================================================
    def generate_advanced_summary(
        self,
        pages_data: List[Dict[str, Any]],
        document_title: str = "Uploaded PDF",
        summary_type: str = "Detailed Summary",
        length: str = "Detailed",
        topic: Optional[str] = None,
        level: str = "Intermediate",
        language: str = "English",
        action: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generates high-quality academic summaries by analyzing all readable PDF pages:
          Types:
            1. Quick Summary (Short overview, main ideas, key takeaways)
            2. Detailed Summary (Complete narrative of all major topics, definitions, examples)
            3. Chapter-wise Summary (Separate summary for every chapter with key concepts)
            4. Exam Notes (Important definitions, exam questions, comparison tables, formulas)
            5. Last-Minute Revision (High-yield bullets, short definitions, formulas, memory triggers)
            6. Topic-wise Summary (Summarize a particular user-selected topic using PDF content)
          Length Control:
            - Short (300-600 words)
            - Medium (800-1500 words)
            - Detailed (1800-3000 words)
            - Very Detailed (3500+ words)
        """
        total_pages = len(pages_data)

        # Filter by topic if requested
        relevant_pages = pages_data
        if topic and topic.strip():
            t_lower = topic.strip().lower()
            filtered = [p for p in pages_data if t_lower in p.get("text", "").lower()]
            if filtered:
                relevant_pages = filtered

        # Prepare text excerpts preserving page provenance
        page_texts = []
        for p in relevant_pages:
            p_num = p.get("page_number", 1)
            txt = p.get("text", "").strip()
            if txt:
                page_texts.append(f"[Page {p_num}]:\n{txt}")

        aggregated_text = "\n\n".join(page_texts)

        # Truncate gracefully if extremely large (e.g. 50+ pages), preserving balanced samples
        if len(aggregated_text) > 30000:
            sample_per_page = 30000 // max(1, len(relevant_pages))
            compact_pages = []
            for p in relevant_pages:
                p_num = p.get("page_number", 1)
                txt = p.get("text", "").strip()
                compact_pages.append(f"[Page {p_num}]:\n{txt[:sample_per_page]}")
            aggregated_text = "\n\n".join(compact_pages)

        # Length target guidelines
        length_targets = {
            "Short": "Length target: 350-500 words. Be concise, punchy, high-yield.",
            "Medium": "Length target: 800-1200 words. Balanced depth, clear explanations.",
            "Detailed": "Length target: 1800-2500 words. Comprehensive coverage of all topics, subtopics, and formulas.",
            "Very Detailed": "Length target: 3000+ words. Exhaustive masterclass university breakdown covering all mechanisms, proofs, and examples."
        }
        length_guideline = length_targets.get(length, length_targets["Detailed"])

        # Type-specific prompt instructions
        type_instructions = {
            "Quick Summary": (
                "Task: Generate a QUICK EXECUTIVE SUMMARY.\n"
                "- Provide an executive overview (3-5 sentences).\n"
                "- Core thesis and central ideas.\n"
                "- 6-8 key takeaways.\n"
                "- Simple, student-friendly language."
            ),
            "Detailed Summary": (
                "Task: Generate a COMPLETE DETAILED ACADEMIC SUMMARY.\n"
                "- Comprehensive narrative covering every major topic and subtopic.\n"
                "- Full conceptual explanations, definitions, and mechanisms.\n"
                "- Real-world examples and practical applications.\n"
                "- Proper hierarchical headings and subheadings."
            ),
            "Chapter-wise Summary": (
                "Task: Generate a CHAPTER-WISE SUMMARY.\n"
                "- Break down the document chapter-by-chapter (or section-by-section).\n"
                "- For each chapter: Chapter Title, Page Range, Chapter Introduction, Topic-wise Breakdown, Key Concepts, and Conclusion."
            ),
            "Exam Notes": (
                "Task: Generate HIGH-YIELD EXAM PREPARATION NOTES.\n"
                "- Critical Definitions & Terminology glossary with page citations.\n"
                "- Frequently examinable concepts & model Short-Answer Q&A.\n"
                "- Model Long-Answer questions with structured outlines.\n"
                "- Comparison & Differences table between confusing terms.\n"
                "- Key Formulas, Laws, Algorithms, and Exam Tips."
            ),
            "Last-Minute Revision": (
                "Task: Generate LAST-MINUTE REVISION SHEETS.\n"
                "- Ultra-dense high-yield bullet points only.\n"
                "- 1-line definitions for rapid recall.\n"
                "- Formulas, equations, and facts.\n"
                "- Fast memory triggers and mnemonics."
            ),
            "Topic-wise Summary": (
                f"Task: Generate a FOCUSED TOPIC SUMMARY on '{topic or 'Core Topic'}'.\n"
                "- Explain this specific topic in complete depth using the PDF excerpts.\n"
                "- Cover background, definitions, mechanism, examples, and exam significance."
            )
        }
        selected_type_guideline = type_instructions.get(summary_type, type_instructions["Detailed Summary"])

        system_instruction = (
            "You are an elite academic professor, curriculum designer, and textbook author. "
            "Your task is to analyze the uploaded course material and synthesize a masterclass academic study document. "
            "Never invent facts or cite things not present in the text.\n\n"
            f"SUMMARY SPECIFICATIONS:\n"
            f"- Type: {summary_type}\n"
            f"- {selected_type_guideline}\n"
            f"- {length_guideline}\n"
            f"- Target Audience: University / College student ({level} level).\n\n"
            "OUTPUT FORMAT:\n"
            "Output a STRICT JSON object with these exact keys:\n"
            "{\n"
            '  "summary_type": "' + summary_type + '",\n'
            '  "title": "Clear descriptive title",\n'
            '  "executive_summary": "Concise overview",\n'
            '  "detailed_content": "Full markdown formatted comprehensive study content with proper #, ##, ### headings, bullet points, and tables",\n'
            '  "chapter_breakdown": [\n'
            '    {\n'
            '      "title": "Chapter / Section Name",\n'
            '      "pages": "Pages X-Y",\n'
            '      "summary": "Detailed summary",\n'
            '      "key_takeaways": ["Point 1", "Point 2"]\n'
            '    }\n'
            '  ],\n'
            '  "exam_notes": ["Exam note 1", "Exam note 2", ...],\n'
            '  "key_definitions": [\n'
            '    {"term": "Term", "definition": "Definition", "page": 1}\n'
            '  ],\n'
            '  "formulas": [\n'
            '    {"name": "Formula Name", "expression": "Expression", "description": "Explanation"}\n'
            '  ],\n'
            '  "important_topics": ["Topic 1", "Topic 2", ...]\n'
            "}"
        )

        prompt = (
            f"DOCUMENT TITLE: {document_title}\n"
            f"TOTAL PAGES ANALYZED: {len(relevant_pages)}\n"
            f"SUMMARY TYPE REQUESTED: {summary_type}\n"
            f"LENGTH SETTING: {length}\n"
            f"{f'FOCUS TOPIC: {topic}' if topic else ''}\n\n"
            f"DOCUMENT SOURCE EXCERPTS:\n{aggregated_text}\n\n"
            f"Synthesize the complete academic summary in valid JSON:"
        )

        try:
            raw_json = self.generate_raw_text(prompt, system_instruction=system_instruction, json_mode=True, temperature=0.2)
            parsed = json.loads(raw_json)

            exec_sum = parsed.get("executive_summary", "")
            detailed_md = parsed.get("detailed_content", "")
            chapters = parsed.get("chapter_breakdown", [])
            exam_notes = parsed.get("exam_notes", [])
            definitions = parsed.get("key_definitions", [])
            formulas = parsed.get("formulas", [])
            topics = parsed.get("important_topics", [])

            # Ensure markdown_summary is rich and complete
            if not detailed_md or len(detailed_md.strip()) < 100:
                detailed_md = f"# {parsed.get('title', document_title)}\n\n{exec_sum}\n\n"
                if chapters:
                    detailed_md += "## Chapter Breakdown\n"
                    for ch in chapters:
                        detailed_md += f"### {ch.get('title', 'Chapter')} ({ch.get('pages', '')})\n{ch.get('summary', '')}\n\n"

            return {
                "document_title": document_title,
                "summary_type": summary_type,
                "length": length,
                "topic": topic,
                "total_pages_analyzed": len(relevant_pages),
                "title": parsed.get("title", f"{summary_type} - {document_title}"),
                "executive_summary": exec_sum,
                "short_summary": exec_sum,
                "detailed_summary": detailed_md,
                "markdown_summary": detailed_md,
                "chapter_summary": chapters,
                "chapter_breakdown": chapters,
                "exam_notes": exam_notes,
                "key_definitions": definitions,
                "formulas_and_algorithms": formulas,
                "important_topics": topics,
                "key_concepts": [d.get("term") for d in definitions[:10]] if definitions else topics[:10]
            }

        except Exception as e:
            logger.error(f"Advanced summary generation error: {e}")
            raise e

    def generate_comprehensive_summary(
        self,
        pages_data: List[Dict[str, Any]],
        document_title: str = "Uploaded PDF"
    ) -> Dict[str, Any]:
        """Backward-compatible default summary generator."""
        return self.generate_advanced_summary(
            pages_data=pages_data,
            document_title=document_title,
            summary_type="Detailed Summary",
            length="Detailed"
        )

    # =========================================================================
    # 3. QUIZ: DYNAMIC GEMINI MCQ GENERATION (100% GENERATED FROM PDF)
    # =========================================================================
    def generate_dynamic_quiz(
        self,
        chunks: List[Dict[str, Any]],
        count: int = 5,
        difficulty: str = "Medium",
        topic: Optional[str] = None,
        document_title: str = "Uploaded PDF"
    ) -> List[Dict[str, Any]]:
        """
        Gemini reads the selected PDF chunks and generates dynamic, rigorous MCQs.
        Each question contains 4 distinct options, exactly 1 correct answer index,
        detailed conceptual explanation, and page provenance.
        """
        count = max(1, min(25, count))

        # Filter chunks by topic or chapter if provided
        filtered_chunks = chunks
        if topic and topic.strip():
            t_lower = topic.strip().lower()
            matched = [c for c in chunks if t_lower in c.get("content", "").lower() or t_lower in c.get("chapter", "").lower()]
            if matched:
                filtered_chunks = matched

        context_samples = []
        for i, c in enumerate(filtered_chunks[:16]):
            p = c.get("page_number", 1)
            content = c.get("content", "").strip()
            chap = c.get("chapter", "")
            prefix = f"[Page {p} | {chap}]:" if chap else f"[Page {p}]:"
            context_samples.append(f"{prefix} {content[:450]}")

        combined_context = "\n\n".join(context_samples)

        topic_instruction = f"Target Topic / Chapter Focus: '{topic}'." if topic else "Cover diverse foundational and applied topics from the reading."

        system_instruction = (
            "You are an academic exam creator for university examinations. "
            "Your task is to generate rigorous, high-yield Multiple Choice Questions (MCQs) "
            "based strictly on the provided study material excerpts.\n\n"
            "RULES:\n"
            f"1. Generate exactly {count} unique MCQs at {difficulty.upper()} difficulty.\n"
            "2. Each question MUST have exactly 4 distinct options (choices A, B, C, D).\n"
            "3. Exactly ONE option must be correct. Specify 'correct_answer_index' as an integer (0, 1, 2, or 3).\n"
            "4. Provide a detailed 'explanation' justifying why the correct choice is true based on the document and why distractors are false.\n"
            "5. Cite the exact 'page_number' from the excerpts where the concept appears.\n"
            "6. Output a STRICT JSON array of objects with keys: "
            "'question' (string), 'options' (array of 4 strings), 'correct_answer_index' (integer 0-3), "
            "'explanation' (string), 'topic' (string), 'page_number' (integer)."
        )

        prompt = (
            f"DOCUMENT TITLE: {document_title}\n"
            f"DIFFICULTY LEVEL: {difficulty}\n"
            f"{topic_instruction}\n\n"
            f"DOCUMENT EXCERPTS:\n{combined_context}\n\n"
            f"Generate {count} MCQs in valid JSON:"
        )

        try:
            raw_json = self.generate_raw_text(prompt, system_instruction=system_instruction, json_mode=True, temperature=0.25)
            quiz_items = json.loads(raw_json)

            if isinstance(quiz_items, list) and len(quiz_items) > 0:
                validated_questions = []
                for idx, q in enumerate(quiz_items[:count]):
                    opts = q.get("options", [])
                    if isinstance(opts, list) and len(opts) == 4 and "question" in q:
                        c_idx = int(q.get("correct_answer_index", 0))
                        c_idx = max(0, min(3, c_idx))
                        validated_questions.append({
                            "id": idx + 1,
                            "question": q["question"],
                            "options": opts,
                            "correct_answer_index": c_idx,
                            "correct_index": c_idx,
                            "explanation": q.get("explanation", f"Verified from Page {q.get('page_number', 1)}."),
                            "page_number": int(q.get("page_number", 1)),
                            "topic": q.get("topic", topic or "Core Syllabus"),
                            "difficulty": difficulty
                        })

                if validated_questions:
                    return validated_questions

        except Exception as e:
            logger.error(f"Dynamic quiz generation failed: {e}")
            raise e

