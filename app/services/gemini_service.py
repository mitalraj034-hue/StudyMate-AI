    def generate_dynamic_flashcards(
        self,
        chunks: List[Dict[str, Any]],
        count: int = 8,
        topic: Optional[str] = None,
        document_title: str = "Uploaded PDF"
    ) -> List[Dict[str, Any]]:
        """
        Gemini reads the selected PDF chunks and generates active-recall flashcards.
        Front: Key question, term, formula, or concept.
        Back: Clear, accurate answer with explanation and page citation.
        """
        count = max(1, min(30, count))

        filtered_chunks = chunks
        if topic and topic.strip():
            t_lower = topic.strip().lower()
            matched = [c for c in chunks if t_lower in c.get("content", "").lower() or t_lower in c.get("chapter", "").lower()]
            if matched:
                filtered_chunks = matched

        context_samples = []
        for c in filtered_chunks[:18]:
            p = c.get("page_number", 1)
            content = c.get("content", "").strip()
            chap = c.get("chapter", "")
            prefix = f"[Page {p} | {chap}]:" if chap else f"[Page {p}]:"
            context_samples.append(f"{prefix} {content[:400]}")

        combined_context = "\n\n".join(context_samples)
        topic_info = f"Focus Topic / Chapter: '{topic}'." if topic else "Cover diverse key terms, formulas, and principles."

        system_instruction = (
            "You are an active-recall flashcard creator for university students. "
            "Generate high-yield conceptual flashcards for spaced repetition study based strictly on the text.\n\n"
            "RULES:\n"
            f"1. Generate exactly {count} distinct active-recall flashcards.\n"
            "2. 'front': An important question, definition prompt, formula inquiry, or core concept.\n"
            "3. 'back': An accurate, concise, crystal-clear explanation with necessary details.\n"
            "4. Include key definitions, technical terms, formulas, and exam facts.\n"
            "5. Cite the exact 'page_number' from the excerpts.\n"
            "6. Output a STRICT JSON array of objects with keys: 'front' (string), 'back' (string), 'topic' (string), 'page_number' (integer)."
        )

        prompt = (
            f"DOCUMENT: {document_title}\n"
            f"{topic_info}\n\n"
            f"SOURCE MATERIAL:\n{combined_context}\n\n"
            f"Generate {count} active recall flashcards in valid JSON:"
        )

        try:
            raw_json = self.generate_raw_text(prompt, system_instruction=system_instruction, json_mode=True, temperature=0.25)
            cards_data = json.loads(raw_json)

            if isinstance(cards_data, list) and len(cards_data) > 0:
                validated_cards = []
                for idx, c in enumerate(cards_data[:count]):
                    if "front" in c and "back" in c:
                        validated_cards.append({
                            "id": idx + 1,
                            "front": c["front"],
                            "back": c["back"],
                            "question": c["front"],
                            "answer": c["back"],
                            "topic": c.get("topic", topic or "Key Concept"),
                            "page_number": int(c.get("page_number", 1))
                        })
                if validated_cards:
                    return validated_cards

        except Exception as e:
            logger.error(f"Dynamic flashcard generation failed: {e}")
            raise e

