    # =========================================================================
    # 6. DENSE EMBEDDINGS FOR PGVECTOR & CHROMADB (768 DIMENSIONS)
    # =========================================================================
    def generate_embedding(self, text: str) -> List[float]:
        """
        Generates 768-dimensional dense vector embeddings for Supabase pgvector & ChromaDB.
        Uses gemini-embedding-001 with normalized fallback.
        """
        key = self.get_api_key()
        if key and GENAI_AVAILABLE:
            if self.client is None:
                self._init_sdk_client()
            if self.client:
                try:
                    res = self.client.models.embed_content(
                        model="gemini-embedding-001",
                        contents=text[:2000]
                    )
                    vals = None
                    if res and hasattr(res, "embeddings") and res.embeddings:
                        first = res.embeddings[0] if isinstance(res.embeddings, list) else res.embeddings
                        vals = getattr(first, "values", None)
                    elif res and hasattr(res, "embedding") and res.embedding:
                        vals = getattr(res.embedding, "values", None)

                    if vals:
                        if len(vals) >= self.dimension:
                            return list(vals[:self.dimension])
                        return list(vals) + [0.0] * (self.dimension - len(vals))
                except Exception as e:
                    logger.warning(f"google-genai embed_content notice: {e}")

        # Deterministic 768-dim normalized embedding fallback
        tokens = re.findall(r'\b[a-zA-Z0-9_\-]{2,}\b', text.lower())
        vec = [0.0] * self.dimension
        if not tokens:
            return vec

        token_counts = Counter(tokens)
        for token, count in token_counts.items():
            bucket = abs(hash(token)) % self.dimension
            sign = 1.0 if (hash(token + "_sign") % 2 == 0) else -1.0
            weight = (1.0 + math.log(count)) * sign
            vec[bucket] += weight

        norm = math.sqrt(sum(x * x for x in vec))
        if norm > 0:
            vec = [round(x / norm, 6) for x in vec]
        return vec

